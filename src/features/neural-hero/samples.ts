/**
 * Hand-drawn sample digits as pen strokes in a 0…1 box (x right, y down).
 * Used for the idle animation and the keyboard-accessible "try a sample"
 * buttons. scripts/test-hero.ts checks the network reads each one correctly.
 */
import type { Stroke } from './raster';

const ellipse = (cx: number, cy: number, rx: number, ry: number, steps = 28): Stroke =>
  Array.from({ length: steps + 1 }, (_, i) => {
    const t = -Math.PI / 2 + (i / steps) * Math.PI * 2;
    return [cx + rx * Math.cos(t), cy + ry * Math.sin(t)] as const;
  });

